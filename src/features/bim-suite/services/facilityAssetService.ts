const TABLE = 'bim_assets';

export async function getProjectAssets(projectId: string): Promise<FacilityAsset[]> {
  return readAllRows<FacilityAsset>((from, to, count) =>
    legacyDb
      .from(TABLE)
      .select('*', count ? { count: 'exact' } : undefined)
      .eq('project_id', projectId)
      .order('created_at', { ascending: false })
      .order('asset_id')
      .range(from, to),
  );
}

export async function createAsset(asset: FacilityAssetInsert): Promise<FacilityAsset> {
  const { data, error } = await legacyDb.from(TABLE).insert(withoutGeneratedFields(asset)).select().single();
  if (error) throw new Error(error.message);
  return data as FacilityAsset;
}

export async function updateAsset(assetId: string, updates: FacilityAssetUpdate): Promise<FacilityAsset> {
  const { data, error } = await legacyDb
    .from(TABLE)
    .update(withoutGeneratedFields(updates))
    .eq('asset_id', assetId)
    .select()
    .single();
  if (error) throw new Error(error.message);
  return data as FacilityAsset;
}

export async function deleteAsset(assetId: string): Promise<void> {
  const { error } = await legacyDb.from(TABLE).delete().eq('asset_id', assetId);
  if (error) throw new Error(error.message);
}

/** Number of assets bound to a model element (bim_element_id set). */
export async function getProjectBimAssetCount(projectId: string): Promise<number> {
  const { count, error } = await legacyDb
    .from(TABLE)
    .select('*', { count: 'exact', head: true })
    .eq('project_id', projectId)
    .not('bim_element_id', 'is', null);
  if (error) return 0;
  return count || 0;
}
