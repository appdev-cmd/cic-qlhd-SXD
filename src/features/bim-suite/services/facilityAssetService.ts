// Asset register (table bim_assets; ACC Build › Assets). Columns keep the English names of cic-hud's facility_assets
// view so the ported operations code reads the same shape. No HUD local release overlay, no demo/actual split.
import { legacyDb } from '../lib/bimDb';
import { readAllRows } from '../lib/readAllRows';

export interface FacilityDocument {
  title: string;
  url: string;
  /** Field photo / completion confirmation attached to a work order. */
  kind?: 'document' | 'photo' | 'signature';
  gps?: string | null;
  taken_at?: string;
}

export interface FacilityAsset {
  asset_id: string;
  project_id: string;
  asset_code: string | null;
  asset_name: string;
  category: string | null;
  location: string | null;
  manufacturer: string | null;
  model: string | null;
  contractor: string | null;
  purchase_cost: number | null;
  warranty_provider: string | null;
  install_date: string | null;
  warranty_expiry: string | null;
  last_maintenance: string | null;
  next_maintenance: string | null;
  maintenance_cycle_days: number | null;
  status: 'Active' | 'Maintenance' | 'Broken' | 'Retired';
  condition: 'Good' | 'Fair' | 'Poor' | 'Critical';
  notes: string | null;
  bim_element_id: string | null;
  created_at: string;
  updated_at: string;
  handover_status?: 'unknown' | 'pending' | 'handed_over';
  handover_date?: string | null;
  location_building?: string | null;
  location_floor?: string | null;
  location_room?: string | null;
  model_id?: string | null;
  documents?: FacilityDocument[];
  /** Typed date columns generated by the database from the text columns. */
  next_maintenance_on?: string | null;
  last_maintenance_on?: string | null;
  install_on?: string | null;
  warranty_expiry_on?: string | null;
  /** Floor/space entities (facility_floors / facility_spaces), system and serial number. */
  floor_key?: string | null;
  space_code?: string | null;
  system_name?: string | null;
  serial_number?: string | null;
}

export type FacilityAssetInsert = Omit<FacilityAsset, 'asset_id' | 'created_at' | 'updated_at'>;
export type FacilityAssetUpdate = Partial<
  Omit<
    FacilityAsset,
    | 'asset_id'
    | 'project_id'
    | 'created_at'
    | 'updated_at'
    | 'next_maintenance_on'
    | 'last_maintenance_on'
    | 'install_on'
    | 'warranty_expiry_on'
  >
>;
/** Generated columns: never sent on write. */
export const GENERATED_ASSET_FIELDS = [
  'next_maintenance_on',
  'last_maintenance_on',
  'install_on',
  'warranty_expiry_on',
] as const;
export const withoutGeneratedFields = <T extends object>(row: T): T =>
  Object.fromEntries(
    Object.entries(row).filter(([key]) => !(GENERATED_ASSET_FIELDS as readonly string[]).includes(key)),
  ) as T;

